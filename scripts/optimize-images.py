"""Generate responsive product images without changing their artwork.
Run with Python 3 and Pillow (WebP and AVIF encoders required).
Also publish immutable content-hashed copies, the React manifest and quiz URLs.
"""
import hashlib
import json
import re
from pathlib import Path

from PIL import Image


def publish_assets(root):
    """Publish exact encoded bytes and update both variants' asset references."""
    output = root / 'public/images'
    versioned = root / 'public/assets'
    versioned.mkdir(parents=True, exist_ok=True)
    manifest = {}
    urls = {}
    for source in sorted(output.glob('*_POTES-*.*')):
        match = re.fullmatch(r'(\d+)_POTES-(256|512|768)\.(avif|webp)', source.name)
        if not match:
            continue
        bottles, width, extension = match.groups()
        data = source.read_bytes()
        digest = hashlib.sha256(data).hexdigest()[:12]
        filename = f'{source.stem}-{digest}.{extension}'
        (versioned / filename).write_bytes(data)
        url = f'/assets/{filename}'
        manifest.setdefault(bottles, {}).setdefault(width, {})[extension] = url
        urls[(bottles, width, extension)] = url

    # Sorted keys keep generated TypeScript deterministic across runs.
    (root / 'src/productImages.ts').write_text(
        '// Generated by scripts/optimize-images.py; do not edit asset hashes by hand.\n'
        + 'export const productImages = '
        + json.dumps(manifest, indent=2, sort_keys=True)
        + ' as const;\n',
        encoding='utf-8',
    )
    quiz_path = root / 'variante-b.html'
    quiz = quiz_path.read_text(encoding='utf-8')
    quiz = re.sub(
        r'/assets/(\d+)_POTES-(256|512|768)-[0-9a-f]{12}\.(avif|webp)',
        lambda match: urls.get(match.groups(), match[0]),
        quiz,
    )
    quiz_path.write_text(quiz, encoding='utf-8')


def main():
    root = Path(__file__).resolve().parents[1]
    output = root / 'public/images'
    output.mkdir(parents=True, exist_ok=True)
    for source in sorted((root / 'assets/source-images').glob('*.png')):
        with Image.open(source) as original:
            for width in (256, 512, 768):
                height = round(original.height * width / original.width)
                resized = original.resize((width, height), Image.Resampling.LANCZOS)
                for extension, options in (
                    ('webp', {'quality': 84, 'method': 6}),
                    ('avif', {'quality': 70, 'speed': 6}),
                ):
                    target = output / f'{source.stem}-{width}.{extension}'
                    resized.save(target, **options)
                    print(f'{target.name}: {target.stat().st_size:,} bytes')
    publish_assets(root)


if __name__ == '__main__':
    main()
